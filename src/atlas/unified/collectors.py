"""Collectors: one function per coverage row, each returning subject -> Cell.

A collector only reads; it never invents. Rows without a collector are reported
as fully unsearched, so the table is complete from day one and can only improve.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

import yaml

from atlas.unified.cells import Cell
from atlas.unified.geo import normalize_distribution
from atlas.unified.identity import Edge
from atlas.unified.store import Store


@dataclass
class Universe:
    species: dict[str, dict]                       # discovery pool, keyed by lower-case binomial
    products: list[str] = field(default_factory=list)   # product ids of all catalog records
    edges: list[Edge] = field(default_factory=list)
    store: Store | None = None
    ledger: dict[str, set[str]] = field(default_factory=dict)   # claim group -> binomials with a curated claim


def load_pool(root: Path) -> dict[str, dict]:
    path = root / "data/research/scope/species-pool.yaml"
    loader = getattr(yaml, "CSafeLoader", yaml.SafeLoader)
    return yaml.load(path.read_text(encoding="utf-8"), Loader=loader)["pool"]


def _epd_text_cell(entry: dict, value) -> Cell:
    """Context cell: present -> CONTEXT; profile read but empty -> SEARCHED_EMPTY; no profile -> UNSEARCHED."""
    if value:
        return Cell.CONTEXT
    epd = entry.get("epd")
    is_epd = bool((epd or {}).get("path")) or isinstance(epd, dict) or "epd-zim" in entry.get("sources", [])
    return Cell.SEARCHED_EMPTY if is_epd else Cell.UNSEARCHED


def species_identity(u: Universe) -> dict[str, Cell]:
    # Pool membership is discovery context; only a ledger node makes identity a claim.
    return {b: Cell.FILLED if e.get("in_atlas") else Cell.CONTEXT for b, e in u.species.items()}


def common_names(u: Universe) -> dict[str, Cell]:
    return {b: _epd_text_cell(e, e.get("common_names")) for b, e in u.species.items()}


def distribution(u: Universe) -> dict[str, Cell]:
    cells = {
        b: _epd_text_cell(e, normalize_distribution((e.get("epd") or {}).get("distribution")))
        for b, e in u.species.items()
    }
    for group in ("geography", "origin"):
        for b, c in _group_cells(u, group).items():
            if c is Cell.FILLED or cells.get(b) != Cell.FILLED:
                cells[b] = c
    return cells


def edible_parts(u: Universe) -> dict[str, Cell]:
    return {b: _epd_text_cell(e, (e.get("epd") or {}).get("edible_parts")) for b, e in u.species.items()}


def food_hierarchy(u: Universe) -> dict[str, Cell]:
    """Product axis: a product is resolved once it carries a decision (approved or rejected)."""
    decided = {e.product for e in u.edges}
    return {p: Cell.FILLED for p in u.products if p in decided}


def _group_cells(u: Universe, group: str) -> dict[str, Cell]:
    """Species-axis cells for one claim group: curated ledger claims + bulk store, joined through edges."""
    cells: dict[str, Cell] = {}
    if u.store is not None:
        cells.update({b: Cell.SEARCHED_EMPTY for b in u.store.species_searched_empty(group)})
        cells.update({b: Cell.FILLED for b in u.store.species_with_claims(group)})
    cells.update({b: Cell.FILLED for b in u.ledger.get(group, ())})
    return {b: c for b, c in cells.items() if b in u.species}


def nutrients(u: Universe) -> dict[str, Cell]:
    return _group_cells(u, "nutrition")


def molecules(u: Universe) -> dict[str, Cell]:
    return _group_cells(u, "molecules")


def bioactivity(u: Universe) -> dict[str, Cell]:
    return _group_cells(u, "bioactivity")


def seasonality(u: Universe) -> dict[str, Cell]:
    return _group_cells(u, "season")


def growing(u: Universe) -> dict[str, Cell]:
    cells = {b: _epd_text_cell(e, (e.get("epd") or {}).get("grow")) for b, e in u.species.items()}
    cells.update(_group_cells(u, "growing"))
    return cells


COLLECTORS: dict[str, Callable[[Universe], dict[str, Cell]]] = {
    "species_identity": species_identity, "common_names": common_names, "distribution": distribution,
    "edible_parts": edible_parts, "food_hierarchy": food_hierarchy, "nutrients": nutrients,
    "molecules": molecules, "bioactivity": bioactivity, "seasonality": seasonality,
    "growing": growing,
}


EDGES_PATH = "data/registry/identity/edges.jsonl"   # tracked in Git: the approved identity decisions
STORE_PATH = "data/build/unified.duckdb"            # derived, regenerated by `atlas ingest`


def ledger_species(payload: dict) -> dict[str, set[str]]:
    """Claim group -> species (binomials) that own a curated claim; cultivars and parts count for their species."""
    organisms = {o["id"]: o for o in payload.get("organisms") or []}

    def binomial(org_id: str | None) -> str:
        while org_id in organisms and organisms[org_id].get("parent"):
            org_id = organisms[org_id]["parent"]
        return " ".join(str((organisms.get(org_id) or {}).get("name") or "").split()).lower()

    out: dict[str, set[str]] = {}
    for food in payload.get("foods") or []:
        for c in food.get("claims") or []:
            out.setdefault(c["group"], set()).add(binomial(food.get("taxon")))
    for org in organisms.values():
        for c in org.get("claims") or []:
            out.setdefault(c["group"], set()).add(binomial(org["id"]))
    return {g: {b for b in bs if b} for g, bs in out.items()}


def load_universe(root: Path, with_products: bool = True) -> Universe:
    """Everything a collector may read: pool (with the current ledger overlay), products, decisions, store."""
    import json

    from atlas.unified.identity import load_edges, product_id

    # Check if _library_species exists in atlas.site.species or atlas.foods
    try:
        from atlas.site.species import _library_species
    except ImportError:
        def _library_species(payload: dict) -> dict[str, str]:
            orgs = {o["id"]: o for o in payload.get("organisms") or []}
            res = {}
            for f in payload.get("foods") or []:
                if f.get("level") == "taxon_food" and f.get("taxon"):
                    org = orgs.get(f["taxon"])
                    if org and org.get("name"):
                        res[org["name"].lower()] = f["id"]
            return res

    pool = load_pool(root)
    payload_path = root / "data/build/atlas.json"
    ledger: dict[str, set[str]] = {}
    if payload_path.is_file():
        payload = json.loads(payload_path.read_text(encoding="utf-8"))
        library = _library_species(payload)
        for b, entry in pool.items():
            entry["in_atlas"] = b in library     # stale pool flags never count
        ledger = ledger_species(payload)
    products: list[str] = []
    if with_products:
        from atlas.site import catalog
        products = [product_id(r["source"], r["id"]) for r in catalog._fdc_rows() + catalog._bls_rows()]
    edges = load_edges(root / EDGES_PATH)
    store_file = root / STORE_PATH
    store = Store(store_file) if store_file.is_file() else None
    if store is not None:
        store.load_edges(edges)
    return Universe(species=pool, products=products, edges=edges, store=store, ledger=ledger)
